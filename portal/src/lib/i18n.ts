export type TranslationKey = keyof typeof ko

const dictionaries: Record<Locale, Record<TranslationKey, string>> = { ko, en }

export function t(locale: Locale, key: TranslationKey, params?: Record<string, string | number>): string {
  const text = dictionaries[locale][key] ?? dictionaries[defaultLocale][key] ?? key
  if (!params) return text
  return text.replace(/\{(\w+)\}/g, (match, k) => (k in params ? String(params[k]) : match))
}

/** Resolves a compliance accepted-reason i18n key in the active locale with English fallback. */
export function translateAcceptedReason(
  locale: Locale,
  reasonKey?: string,
  fallback?: string,
): string | undefined {
  if (reasonKey && Object.prototype.hasOwnProperty.call(dictionaries[locale], reasonKey)) {
    return dictionaries[locale][reasonKey as TranslationKey]
  }
  return fallback
}

